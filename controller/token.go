func GetTokenStatus(c *gin.Context) {
	tokenId := c.GetInt(ctxkey.TokenId)
	userId := c.GetInt(ctxkey.Id)
	token, err := model.GetTokenByIds(tokenId, userId)
	if err != nil {
		c.JSON(http.StatusOK, gin.H{
			"success": false,
			"message": err.Error(),
		})
		return
	}
	expiredAt := token.ExpiredTime
	if expiredAt == -1 {
		expiredAt = 0
	}
	c.JSON(http.StatusOK, gin.H{
		"object":          "credit_summary",
		"total_granted":   token.RemainQuota,
		"total_used":      0, // not supported currently
		"total_available": token.RemainQuota,
		"expires_at":      expiredAt * 1000,
	})
}

func validateToken(c *gin.Context, token model.Token) error {
	if len(token.Name) > 30 {
		return errors.New(i18n.Translate(c, "token.name_too_long"))
	}
	if token.Subnet != nil && *token.Subnet != "" {
		err := network.IsValidSubnets(*token.Subnet)
		if err != nil {
			return errors.New(i18n.Translatef(c, "token.invalid_subnet", err.Error()))
		}
	}
	if token.Rpm < 0 || token.Tpm < 0 {
		return errors.New(i18n.Translate(c, "token.rate_limit_negative"))
	}
	if token.Concurrency < 0 {
		return errors.New(i18n.Translate(c, "token.concurrency_negative"))
	}
	if token.DailyQuotaLimit < 0 || token.MonthlyQuotaLimit < 0 {
		return errors.New(i18n.Translate(c, "token.budget_negative"))
	}
	// 接口 scope 校验（LTZY-API 新增，C3）：逐个校验模式名，
	// 避免写错一个词就让令牌实际可用范围与管理员预期不符
	if token.AllowedModes != nil && strings.TrimSpace(*token.AllowedModes) != "" {
		for _, modeName := range strings.Split(*token.AllowedModes, ",") {
			modeName = strings.TrimSpace(modeName)
			if modeName == "" {
				continue
			}
			if !relaymode.IsValidName(modeName) {
				return errors.New(i18n.Translatef(c, "token.invalid_allowed_modes", modeName, relaymode.NamesHelp()))
			}
		}
	}
	return nil
}

func AddToken(c *gin.Context) {
	token := model.Token{}
	err := c.ShouldBindJSON(&token)
	if err != nil {
		c.JSON(http.StatusOK, gin.H{
			"success": false,
			"message": err.Error(),
		})
		return
	}
	err = validateToken(c, token)
	if err != nil {
		c.JSON(http.StatusOK, gin.H{
			"success": false,
			"message": i18n.Translatef(c, "token.invalid_params", err.Error()),
		})
		return
	}

	cleanToken := model.Token{
		UserId:         c.GetInt(ctxkey.Id),
		Name:           token.Name,
		Key:            random.GenerateKey(),
		CreatedTime:    helper.GetTimestamp(),
		AccessedTime:   helper.GetTimestamp(),
		ExpiredTime:    token.ExpiredTime,
		RemainQuota:    token.RemainQuota,
		UnlimitedQuota: token.UnlimitedQuota,
		Models:         token.Models,
		Subnet:         token.Subnet,
		// 限速与并发配置（LTZY-API 修复）：此前漏传，导致新建令牌时前端填写的
		// RPM/TPM 被静默丢弃，只有编辑才生效
		Rpm:         token.Rpm,
		Tpm:         token.Tpm,
		Concurrency: token.Concurrency,
		// 预算上限（LTZY-API 新增，B6）
		DailyQuotaLimit:   token.DailyQuotaLimit,
		MonthlyQuotaLimit: token.MonthlyQuotaLimit,
		// 接口 scope（LTZY-API 新增，C3）
		AllowedModes: token.AllowedModes,
	}
	err = cleanToken.Insert()
	if err != nil {
		c.JSON(http.StatusOK, gin.H{
			"success": false,
			"message": err.Error(),
		})
		return
	}
	c.JSON(http.StatusOK, gin.H{
		"success": true,
		"message": "",
		"data":    cleanToken,
	})
	return
}

